create table public.world_course_keys (
 role_id text primary key,
 answers jsonb not null
);
revoke all on public.world_course_keys from anon, authenticated;
alter table public.world_course_keys enable row level security;
create table public.world_course_completions (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references auth.users(id) on delete cascade,
 role_id text not null references public.world_course_keys(role_id),
 learner text not null,
 answers jsonb not null,
 completed_at timestamptz not null default now(),
 unique(user_id,role_id)
);
alter table public.world_course_completions enable row level security;
revoke all on public.world_course_completions from anon, authenticated;
grant select on public.world_course_completions to authenticated;
create policy own_completions on public.world_course_completions for select to authenticated using (user_id = (select auth.uid()));
create function public.complete_world_course(p_role text, p_answers jsonb)
returns public.world_course_completions
language plpgsql security definer set search_path = ''
as $$
declare
 expected jsonb;
 result public.world_course_completions;
 account_name text;
begin
 if auth.uid() is null then raise exception 'Sign in required'; end if;
 select answers into expected from public.world_course_keys where role_id = p_role;
 if expected is null or p_answers is distinct from expected then raise exception 'Complete all course checks'; end if;
 select username into account_name from public.profiles where id = auth.uid();
 if account_name is null then raise exception 'Account profile required'; end if;
 insert into public.world_course_completions(user_id,role_id,learner,answers)
 values(auth.uid(),p_role,account_name,p_answers)
 on conflict(user_id,role_id) do nothing;
 select * into result from public.world_course_completions where user_id=auth.uid() and role_id=p_role;
 return result;
end;
$$;
revoke all on function public.complete_world_course(text,jsonb) from public;
grant execute on function public.complete_world_course(text,jsonb) to authenticated;

