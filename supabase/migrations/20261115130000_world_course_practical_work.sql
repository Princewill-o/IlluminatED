create function public.complete_world_course(p_role text,p_answers jsonb,p_work jsonb)
returns public.world_course_completions
language plpgsql security definer set search_path='' as $$
declare
 expected jsonb;
 expected_total integer;
 account_name text;
 result public.world_course_completions;
begin
 if auth.uid() is null then raise exception 'Sign in required'; end if;
 select answers,work_total into expected,expected_total from public.world_course_keys where role_id=p_role;
 if expected is null or p_answers is distinct from expected then raise exception 'Complete all course checks'; end if;
 if p_work is null or jsonb_typeof(p_work) <> 'object'
 or (p_work->'decisions') is distinct from '{"R1":"accept","R2":"hold","R3":"escalate","R4":"accept"}'::jsonb
 or jsonb_typeof(p_work->'total') is distinct from 'string'
 or (p_work->>'total') !~ '^[0-9]{1,6}$'
 then raise exception 'Complete practical decisions and calculation'; end if;
 if (p_work->>'total')::integer is distinct from expected_total then raise exception 'Check the work total'; end if;
 if jsonb_typeof(p_work->'owner') is distinct from 'string'
 or length(btrim(p_work->>'owner')) < 3 or length(p_work->>'owner') > 100
 or jsonb_typeof(p_work->'handover') is distinct from 'string'
 or length(btrim(p_work->>'handover')) < 80 or length(p_work->>'handover') > 2000
 or (p_work->>'handover') !~* '\mR2\M' or (p_work->>'handover') !~* '\mR3\M'
 then raise exception 'Complete the handover owner and references'; end if;
 select username into account_name from public.profiles where id=auth.uid();
 if account_name is null then raise exception 'Account profile required'; end if;
 insert into public.world_course_completions(user_id,role_id,learner,answers,work)
 values(auth.uid(),p_role,account_name,p_answers,p_work)
 on conflict(user_id,role_id) do update set work = coalesce(public.world_course_completions.work,excluded.work);
 select * into result from public.world_course_completions where user_id=auth.uid() and role_id=p_role;
 return result;
end;
$$;
