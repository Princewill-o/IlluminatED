import test from 'node:test';
import assert from 'node:assert/strict';
import {projectData} from '../scripts/lib/project-data.mjs';
const core=projectData('src/game/core/street-custody.ts');
const law=projectData('src/game/core/law.ts');
const storage=projectData('src/game/core/life-storage.ts');
const caseFile={id:'case-1',npcName:'Alex',npcId:'city:resident:1',charge:'Starting a street scuffle',evidence:{playerHits:1,civilianHits:2}};
test('a court hearing is blocked until officers arrest and deliver the people involved',()=>{
  let state=core.beginStreetCustody(caseFile,1000,5);
  assert.equal(core.canHearStreetCase(caseFile,null),false);
  state=core.advanceStreetCustody(state,2000,true,5);assert.equal(state.stage,'responding');
  state=core.advanceStreetCustody(state,5000,false,5);assert.equal(state.stage,'responding');
  state=core.advanceStreetCustody(state,5000,true,4);assert.equal(state.stage,'responding');
  state=core.advanceStreetCustody(state,5000,true,5);assert.equal(state.stage,'arresting');
  assert.deepEqual(Array.from(state.participants),['player','civilian']);
  assert.equal(core.finishStreetTransport(state,10000),null);
  state=core.advanceStreetCustody(state,7999,true,5);assert.equal(state.stage,'arresting');
  state=core.advanceStreetCustody(state,8000,true,5);assert.equal(state.stage,'transport');
  assert.equal(core.finishStreetTransport(state,8001),null);
  const proof=core.finishStreetTransport(state,11200);assert.ok(proof);
  assert.equal(core.canHearStreetCase(caseFile,proof),true);
  assert.equal(core.canHearStreetCase({...caseFile,id:'other-case'},proof),false);
  assert.equal(core.canHearStreetCase(caseFile,{...proof,participants:['player']}),false);
  assert.equal(core.canHearStreetCase(caseFile,{...proof,arrestedAt:NaN}),false);
});
test('a victim who never hit back is not included in the arrest list',()=>{
  const playerOnly={...caseFile,evidence:{playerHits:1,civilianHits:0}};
  assert.equal(core.beginStreetCustody(playerOnly,0,4),null);
  assert.deepEqual(Array.from(core.beginStreetCustody(playerOnly,0,5).participants),['player']);
  assert.deepEqual(Array.from(core.beginStreetCustody({...caseFile,evidence:{playerHits:0,civilianHits:2}},0,0).participants),['civilian']);
  let npcOnly=core.beginStreetCustody(caseFile,0,4);
  assert.deepEqual(Array.from(npcOnly.participants),['civilian']);
  npcOnly=core.advanceStreetCustody(npcOnly,2500,true,4);
  npcOnly=core.advanceStreetCustody(npcOnly,5500,true,4);
  const proof=core.finishStreetTransport(npcOnly,8500);
  assert.ok(proof);
  assert.equal(core.canHearStreetCase(caseFile,proof),false);
});
test('scuffles add a star and only create a custody case when that reaches five',()=>{
  const report={kind:'aggression',offence:'scuffle',caseFile};
  const first=core.recordStreetIncident(law.freshLife(),report,1000);
  assert.equal(first.stars,1);
  assert.equal(first.hearing,null);
  const third=core.recordStreetIncident({...first,stars:2},report,2000);
  assert.equal(third.stars,3);
  assert.equal(third.hearing,null);
  const fifth=core.recordStreetIncident({...third,stars:4},report,3000);
  assert.equal(fifth.stars,5);
  assert.equal(fifth.hearing.streetCase,caseFile);
  assert.equal(fifth.hearing.stars,5);
  const contested=core.recordStreetIncident(third,{kind:'contested',caseFile},3000);
  assert.equal(contested,third);
});
test('pre-update unserved street cases cannot start a low-star arrest after reloading',()=>{
  const key=storage.lifeStorageKey('pupil');
  const data=new Map();
  const store={getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,value)};
  const hearing={stars:2,charge:caseFile.charge,streetCase:caseFile};
  data.set(key,JSON.stringify({...law.freshLife(),stars:2,heatAt:1000,hearing}));
  assert.equal(storage.readAccountLife(store,'pupil',2000).hearing,null);
  const custody={caseId:caseFile.id,participants:['player','civilian'],arrestedAt:5000,deliveredAt:11000};
  data.set(key,JSON.stringify({...law.freshLife(),hearing:{...hearing,custody}}));
  assert.equal(storage.readAccountLife(store,'pupil',12000).hearing.custody.caseId,caseFile.id);
});
